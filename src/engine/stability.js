/**
 * Heuristics that estimate whether an attribute value is likely to survive
 * re-renders, deployments and data changes. They are intentionally
 * conservative: an unknown value is "medium", never "high" by default.
 */

const GENERATED_ID_PREFIXES = [
  /^ember\d+/i,
  /^ext-(gen|comp|element)/i,
  /^gwt-uid/i,
  /^yui_/i,
  /^react-select-\d+/i,
  /^headlessui-/i,
  /^radix-/i,
  /^mui-\d+/i,
  /^:r[0-9a-z]+:$/i,
  /^«r[0-9a-z]+»$/i,
  /^rc[-_]/i,
  /^j_id/i,
  /^ctl\d+/i,
  /^__next/i,
  /^vs\d+__/i,
  /^v-\d+/i,
  /^ng-\d/i,
  /^cdk-/i,
  /^mat-[a-z-]*\d+/i,
  /^downshift-\d+/i,
  /^tippy-\d+/i,
  /^select2-/i,
  /^ui-id-\d+/i,
  /^id-\d+/i,
  /^__[a-z]/i,
];

const UUID = /[0-9a-f]{8}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{12}/i;
const LONG_DIGITS = /\d{4,}/;
const HEX_HASH = /(^|[-_:])[0-9a-f]{6,}($|[-_:])/i;

/** True when a segment mixes letters and digits like a random hash (e.g. "a8F3k2"). */
function looksRandomSegment(segment) {
  if (segment.length < 5) return false;
  const digits = (segment.match(/\d/g) || []).length;
  const letters = (segment.match(/[a-z]/gi) || []).length;
  if (digits === 0 || letters === 0) return false;
  const transitions = (segment.match(/[a-z]\d|\d[a-z]/gi) || []).length;
  return transitions >= 3 || (digits >= 2 && /[A-Z]/.test(segment) && /[a-z]/.test(segment));
}

/** Returns a 0..1 stability estimate for an id-like value. */
export function idStability(value) {
  const id = String(value ?? '').trim();
  if (!id) return 0;
  if (/^\d+$/.test(id)) return 0.1;
  if (GENERATED_ID_PREFIXES.some((pattern) => pattern.test(id))) return 0.15;
  if (UUID.test(id)) return 0.1;
  if (HEX_HASH.test(id) && /\d/.test(id)) return 0.2;
  if (id.split(/[-_:.]/).some(looksRandomSegment)) return 0.25;
  if (LONG_DIGITS.test(id)) return 0.35;
  if (/\d+$/.test(id)) return 0.6;
  if (id.length > 50) return 0.5;
  return 0.9;
}

export function isDynamicId(value) {
  return idStability(value) < 0.5;
}

const STATE_CLASSES = new Set([
  'active', 'inactive', 'selected', 'focus', 'focused', 'hover', 'hovered', 'disabled',
  'enabled', 'open', 'opened', 'closed', 'show', 'shown', 'hide', 'hidden', 'visible',
  'invisible', 'collapsed', 'expanded', 'checked', 'current', 'loading', 'loaded', 'error',
  'invalid', 'valid', 'dirty', 'pristine', 'touched', 'untouched', 'in', 'fade', 'animated',
  'highlight', 'highlighted', 'pressed', 'dragging', 'sticky', 'fixed', 'empty',
]);

const UTILITY_CLASS = /^(-?(m|p)[trblxyse]?-|w-|h-|min-|max-|text-|bg-|border|rounded|flex|grid|gap-|col-|row-|items-|justify-|self-|place-|font-|leading-|tracking-|shadow|opacity-|z-|top-|left-|right-|bottom-|inset-|overflow-|cursor-|transition|duration-|ease-|transform|translate-|scale-|rotate-|space-|divide-|ring|outline-|sr-only|block$|inline|hidden$|absolute$|relative$|fixed$|static$|sticky$|container$|d-|float-|align-|clearfix$|pull-|offset-)/;

/**
 * Classifies a class name:
 *  - dynamic: generated by CSS-in-JS / CSS modules, or contains hashes
 *  - state:   reflects transient UI state
 *  - utility: presentational utility (Tailwind, Bootstrap helpers)
 *  - semantic: a human-authored, meaningful class
 */
export function classifyClass(className) {
  const name = String(className ?? '');
  if (!name) return 'dynamic';
  const lower = name.toLowerCase();
  if (STATE_CLASSES.has(lower) || /^(is|has|was|ng|v)-/.test(lower) || /--(active|selected|open|disabled|focused|checked|expanded|hover)$/.test(lower)) {
    return 'state';
  }
  if (
    /^css-[a-z0-9]+/i.test(name) ||
    /^sc-[a-z0-9]+/i.test(name) ||
    /^jsx-\d+/.test(name) ||
    /^svelte-[a-z0-9]+/i.test(name) ||
    /^emotion-/.test(name) ||
    /^_[a-z0-9]{5,}$/i.test(name) ||
    /__[a-z0-9]{5,}$/i.test(name) ||
    /_[a-z0-9]{5,}_\d+$/i.test(name) ||
    (/^[a-z]{1,3}[A-Z0-9][a-zA-Z0-9]{4,}$/.test(name) && looksRandomSegment(name)) ||
    UUID.test(name) ||
    LONG_DIGITS.test(name) ||
    name.split(/[-_]/).some(looksRandomSegment)
  ) {
    return 'dynamic';
  }
  if (/[:[\]/!@]/.test(name) || UTILITY_CLASS.test(lower)) return 'utility';
  return 'semantic';
}

export function isDynamicClass(className) {
  return classifyClass(className) === 'dynamic';
}

export function stableClasses(element) {
  return Array.from(element.classList || []).filter((name) => classifyClass(name) === 'semantic');
}

/** 0..1 stability estimate for visible text used as a locator. */
export function textStability(value) {
  const text = String(value ?? '').trim();
  if (!text) return 0;
  let score = 0.85;
  if (/\d/.test(text)) score -= 0.3;
  if (/[$€£¥₹]|\b\d{1,2}[:/.-]\d{1,2}\b/.test(text)) score -= 0.2;
  if (text.length > 40) score -= 0.2;
  else if (text.length > 25) score -= 0.1;
  if (text.length < 2) score -= 0.3;
  return Math.max(0.05, Math.min(1, score));
}

/** 0..1 stability estimate for generic attribute values (name, aria-label, …). */
export function attributeValueStability(value) {
  const text = String(value ?? '').trim();
  if (!text) return 0;
  if (UUID.test(text) || LONG_DIGITS.test(text)) return 0.25;
  if (text.split(/[-_:.\s]/).some(looksRandomSegment)) return 0.3;
  if (text.length > 60) return 0.5;
  if (/\d/.test(text)) return 0.65;
  return 0.85;
}

export function hrefStability(href) {
  const value = String(href ?? '').trim();
  if (!value || value === '#' || /^javascript:/i.test(value)) return 0;
  if (/[?&](session|token|sid|ts|t|_)=|[?&][a-z_]*id=/i.test(value)) return 0.25;
  if (UUID.test(value) || LONG_DIGITS.test(value)) return 0.3;
  if (value.length > 80) return 0.4;
  return 0.7;
}
